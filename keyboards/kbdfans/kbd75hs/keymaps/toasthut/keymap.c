enum {
  TD_CAPS
};

enum LAYERS {
    BASE = 0,
    FUNC = 1,
    ALT  = 2,
    NAV  = 3,
    LEDS = 4
};

uint8_t val_d;

tap_dance_action_t tap_dance_actions[] = {
  [TD_CAPS] = ACTION_TAP_DANCE_DOUBLE(KC_BSPC, KC_CAPS),
};

 void keyboard_post_init_user(void) {
    val_d = rgblight_get_val();
    rgblight_sethsv(8, rgblight_get_sat(), val_d);
    // Customise these values to desired behaviour
    // debug_enable=true;
    // debug_matrix=true;
    // debug_keyboard=true;
    // debug_mouse=true;
}

layer_state_t layer_state_set_user(layer_state_t state) {
    switch (get_highest_layer(state)) {
        case ALT:
        case NAV:
            rgblight_sethsv(254, rgblight_get_sat(), rgblight_get_val());
            break;
        case LEDS:
            rgblight_sethsv(160, rgblight_get_sat(), rgblight_get_val());
            break;
        default:
            rgblight_sethsv(8, rgblight_get_sat(), rgblight_get_val());
            break;
    }
    return state;
}

bool led_update_user(led_t led_state) {
    rgblight_get_val();
    if (led_state.caps_lock) {
        rgblight_sethsv(rgblight_get_hue(), rgblight_get_sat(), 255);
    } else {
        rgblight_sethsv(rgblight_get_hue(), rgblight_get_sat(), val_d);
    }
    return true;
}


