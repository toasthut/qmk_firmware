void rbgControl(layer_state_t state) {
    switch (get_highest_layer(state)) {
        case ALT:
            rgblight_sethsv(251, rgblight_get_sat(), rgblight_get_val());
            break;
        case ERGO:
            rgblight_sethsv(1, rgblight_get_sat(), rgblight_get_val());
            break;
        case NUMS:
            rgblight_sethsv(235, rgblight_get_sat(), rgblight_get_val());
            break;
        case LEDS:
            rgblight_sethsv(160, rgblight_get_sat(), rgblight_get_val());
            break;
        case BASE:
            rgblight_sethsv(8, rgblight_get_sat(), rgblight_get_val());
            break;
    }
    return;
}

layer_state_t layer_state_set_user(layer_state_t state) {
    rbgControl(state);
    return state;
}

bool led_update_user(led_t led_state) {
    rgblight_get_val();
    if (led_state.caps_lock) {
        rgblight_sethsv(rgblight_get_hue(), rgblight_get_sat(), 255);
    } else {
        rgblight_sethsv(rgblight_get_hue(), rgblight_get_sat(), val_d);
    }
    return true;
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case LYRSWP:
            if (!record->event.pressed) {
                return false;
            }
            layer_on(ALT);
            layer_on(ERGO);
            break;
    }
    return true;
}

